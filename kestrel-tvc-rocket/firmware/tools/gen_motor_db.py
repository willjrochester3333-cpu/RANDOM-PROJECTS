#!/usr/bin/env python3
"""Generate firmware/core/include/kestrel/motor_db.hpp from the simulator's motor data and design.json.

For every supported motor this computes, for THIS airframe:
  * a 24-point thrust table,
  * the vehicle pitch inertia and CG->gimbal lever arm vs time (they change as propellant burns),
  * the launch-detection delay (time for thrust/mass to exceed the detect threshold),
  * the nominal (no-wind, vertical) apogee time, used by the backup deploy timer.

Run after changing design.json or motors.json:
    python3 firmware/tools/gen_motor_db.py
"""
import math
import os
import sys

import numpy as np

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "sim"))
from kestrel.rocket import Rocket, Motor, load_design, G0  # noqa: E402

MOTORS = ["TSP-D20", "TSP-E12", "TSP-E20", "Estes-E12", "Estes-D12", "TSP-F35"]   # new motors go at the end (indices are stored in Settings)
DETECT_G = 2.0
NPTS = 24


def resample(motor: Motor, n=NPTS):
    t, F = motor.t, motor.F
    # keep the peak and use denser sampling during ignition transient
    tb = motor.burn_time
    base = np.concatenate([np.linspace(0, min(0.3, tb * 0.2), 8, endpoint=False), np.linspace(min(0.3, tb * 0.2), tb, n - 8)])
    pk = t[np.argmax(F)]
    base[np.argmin(np.abs(base - pk))] = pk
    base = np.unique(np.sort(base))
    while len(base) < n:
        base = np.sort(np.append(base, (base[-1] + base[-2]) / 2))
    Fi = np.interp(base, t, F)
    Fi[-1] = 0.0
    return base, Fi


def nominal_apogee_time(rocket: Rocket):
    dt = 0.002
    h = v = 0.0
    t = 0.0
    while t < 60:
        m = rocket.mass_props(t).mass
        T = rocket.motor.thrust(t)
        D = 0.5 * 1.2 * v * abs(v) * rocket.A_ref * rocket.cd0(max(abs(v), 1), T > 0)
        a = (T - D) / m - G0
        if h <= 0 and a < 0 and t < rocket.motor.burn_time:
            a = 0.0
        v += a * dt
        h += v * dt
        t += dt
        if t > rocket.motor.burn_time and v < 0:
            return t, h
    return t, h


def main():
    d = load_design()
    blocks = []
    report = []
    for name in MOTORS:
        mot = Motor(name)
        r = Rocket(d, mot)
        tt, FF = resample(mot)
        I = [r.mass_props(x).Iyy for x in tt]
        lev = [r.z_pivot - r.mass_props(x).z_cg for x in tt]
        arm = [r.mass_props(x).z_cg - d["avbay"]["imu_z"] / 1000.0 for x in tt]
        m0 = r.mass_props(0).mass
        # first time thrust / mass exceeds the detect threshold (accelerometer reads T/m on the rod)
        ts = np.linspace(0, mot.burn_time, 4000)
        cross = next((x for x in ts if mot.thrust(x) / r.mass_props(x).mass > DETECT_G * G0), mot.burn_time)
        t_ap, h_ap = nominal_apogee_time(r)
        report.append(f"{name:10s} launch-detect +{cross*1000:.0f} ms, nominal apogee {h_ap:.0f} m at {t_ap:.1f} s")
        def lit(v):
            s = f"{v:.6g}"
            if "." not in s and "e" not in s:
                s += ".0"
            return s + "f"
        f = lambda arr: ", ".join(lit(v) for v in arr)
        blocks.append(f"""    {{"{name}", {len(tt)},
     {{{f(tt)}}},
     {{{f(FF)}}},
     {{{f(I)}}},
     {{{f(lev)}}},
     {{{f(arm)}}},
     {mot.burn_time:.4f}f, {cross:.4f}f, {t_ap:.3f}f}}""")
    # airframe constants for the fin-tab mixer (nominal motor, lift-off)
    ra = Rocket(d, Motor(d["launch"]["nominal_motor"]))
    tabE, tab_zcp, tab_r = ra.tab_params()
    fin_deg = ra.fin_angles_deg() + [0.0] * (4 - ra.fin_n)
    air = (f"inline constexpr Airframe kAirframe{{{tabE:.6g}f, {tab_r:.5f}f, {tab_zcp - ra.z_pivot:.5f}f, "
           f"{ra.mass_props(0).Ixx:.6g}f, {{{', '.join(f'{a:.1f}f' for a in fin_deg[:4])}}}}};")
    report.append(f"tab mixer: E={tabE*1e4:.2f} cm^2, r={tab_r*1000:.1f} mm, tab CP {1000*(tab_zcp - ra.z_pivot):+.1f} mm from pivot, "
                  f"Ixx={ra.mass_props(0).Ixx:.2e} kg m^2, fins {fin_deg[:4]}")
    hdr = f"""// AUTO-GENERATED by firmware/tools/gen_motor_db.py from design.json + sim/kestrel/motors.json.
// Do not edit by hand. Thrust data: ThrustCurve.org (RASP files) via the OpenRocket motor database.
#pragma once
#include "config.hpp"

namespace kestrel {{

inline const MotorProfile kMotors[] = {{
{(','+chr(10)).join(blocks)}
}};
constexpr int kNumMotors = {len(MOTORS)};
// fin tabs: E [m^2], force radius [m], tab CP aft of the gimbal pivot [m], roll inertia [kg m^2], fin angles [deg]
{air}
constexpr int kDefaultMotor = {MOTORS.index(d['launch']['nominal_motor'])};   // {d['launch']['nominal_motor']}

}}  // namespace kestrel
"""
    out = os.path.join(ROOT, "firmware", "core", "include", "kestrel", "motor_db.hpp")
    with open(out, "w") as fh:
        fh.write(hdr)
    print("\n".join(report))
    print("wrote", out)


if __name__ == "__main__":
    main()
