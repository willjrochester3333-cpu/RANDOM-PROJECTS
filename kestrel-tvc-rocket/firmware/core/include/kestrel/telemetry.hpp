// Radio telemetry for a SiK 433 MHz radio (Holybro SiK V3) on the board's radio socket.
//
// Frames are MAVLink v1 shaped (0xFE, len, seq, sys, comp, msgid, payload, CRC-16/MCRF4XX with a per-message "extra"
// byte) so that a SiK radio in its default MAVLINK=1 mode keeps every frame whole inside one radio packet (a lost radio
// packet loses whole frames, never half of one) and the ground radio adds its own RADIO_STATUS link-quality frames.
// KESTREL's own frames use message ids 230/231, which no MAVLink ground station decodes (their CRC extras differ).
//
// UK licence-exempt 433 MHz use (ERC Rec 70-03 / IR2030, 433.05-434.79 MHz): <= 10 mW e.r.p. and <= 10 % of each hour
// on air. The radio's TXPOWER is set to 8 dBm on both radios (docs/BUILD_GUIDE.md); the airtime budget below keeps the
// rocket's own transmissions well under 360 s per rolling hour by choosing the frame rates.
//
// Platform independent (no Pico SDK): host-tested in core/tests, and the ground decoder in ground/ mirrors it.
#pragma once
#include <cstddef>
#include <cstdint>

#include "types.hpp"

namespace kestrel::tlm {

constexpr uint8_t kStx = 0xFE;
constexpr uint8_t kSysId = 75;               // 'K'
constexpr uint8_t kCompId = 1;
constexpr size_t kOverhead = 8;              // stx, len, seq, sys, comp, msgid + 2 CRC bytes
constexpr size_t kMaxPayload = 64;

constexpr uint8_t kMsgHeartbeat = 0;         // standard HEARTBEAT: makes our own radio report RADIO_STATUS to the Pico
constexpr uint8_t kCrcHeartbeat = 50;
constexpr uint8_t kMsgRadioStatus = 109;     // standard RADIO_STATUS, generated by the SiK radios themselves
constexpr uint8_t kCrcRadioStatus = 185;
constexpr uint8_t kMsgFast = 230;            // KESTREL_FAST: motion + control, every 10th 500 Hz sample in flight
constexpr uint8_t kCrcFast = 0x4B;
constexpr uint8_t kMsgSlow = 231;            // KESTREL_SLOW: GPS, power, health, flight summary
constexpr uint8_t kCrcSlow = 0x53;

#pragma pack(push, 1)
struct FastPayload {                         // 42 bytes; units as the flash LogRecord (see types.hpp)
    uint32_t t_ms;
    uint8_t state;
    uint8_t flags;
    int16_t gyro_cdps[3];
    int16_t accel_cmss[3];
    float alt_m;
    int16_t vz_cms;
    int16_t tilt_cdeg;
    int16_t gimbal_cdeg[2];                  // y, z
    int16_t q_i16[3];
    int8_t tab_qdeg[4];
    int16_t roll_cdeg;
};
static_assert(sizeof(FastPayload) == 42, "FastPayload layout is shared with ground/mission_control.html");

struct SlowPayload {                         // 46 bytes
    uint32_t t_ms;
    int32_t lat_e7;                          // degrees x 1e7 (full GPS precision)
    int32_t lon_e7;
    int16_t gps_alt_m;
    uint8_t sats;
    uint8_t gps_valid;
    float baro_alt_m;
    uint16_t vbat_mv;
    uint16_t cell1_mv;
    uint16_t servo_mv;
    uint16_t flight_no;
    uint16_t fw_version;
    uint8_t motor_index;
    uint8_t status;                          // StatusBits
    int16_t apogee_dm;                       // highest filtered altitude of this flight, 0.1 m
    uint16_t airtime_ds;                     // this radio's estimated airtime in the last hour, 0.1 s
    uint8_t rssi_local;                      // rocket radio: signal from the ground radio (SiK units, 0 = unknown)
    uint8_t rssi_remote;                     // ground radio: signal from the rocket, as the rocket radio last heard it
    uint16_t log_dropped;
    uint32_t log_records;
    uint8_t deploy_reason;
    uint8_t ground_heard;                    // 1 = a ground-station heartbeat arrived in the last 3 s
};
static_assert(sizeof(SlowPayload) == 46, "SlowPayload layout is shared with ground/mission_control.html");

struct RadioStatus {                         // MAVLink RADIO_STATUS wire order
    uint16_t rxerrors;
    uint16_t fixed;
    uint8_t rssi;
    uint8_t remrssi;
    uint8_t txbuf;                           // % free in the radio's serial buffer
    uint8_t noise;
    uint8_t remnoise;
};
static_assert(sizeof(RadioStatus) == 9, "RADIO_STATUS payload");
#pragma pack(pop)

enum StatusBits : uint8_t {
    ST_IMU_OK = 1, ST_BARO_OK = 2, ST_LOG_OK = 4, ST_AXES_CAL = 8, ST_WARNING = 16, ST_RECOVERY = 32, ST_TABS_ON = 64,
    ST_SETTINGS_SAVED = 128
};

// CRC-16/MCRF4XX (the MAVLink "X.25" checksum): poly 0x1021 reflected, init 0xFFFF, no final xor.
uint16_t crc_x25(const uint8_t* p, size_t n, uint16_t crc = 0xFFFF);
uint8_t crc_extra(uint8_t msgid);            // 0 for an unknown id

// Writes one frame (payload_len + 8 bytes) to out and returns its length (0 if the payload is too long).
size_t encode(uint8_t msgid, uint8_t seq, const void* payload, uint8_t payload_len, uint8_t* out,
              uint8_t sysid = kSysId, uint8_t compid = kCompId);

// Byte-at-a-time frame decoder for MAVLink v1 frames with a known CRC extra (heartbeat, radio status, ours).
// Keeps a small window of received bytes; after a bad candidate it re-scans from the next 0xFE, so a corrupt or
// foreign frame costs only itself. A decoded frame is copied out, so it stays readable while more bytes arrive.
class Decoder {
public:
    bool feed(uint8_t b);                    // true when a complete, CRC-valid frame has just been decoded
    uint8_t msgid() const { return frame_[5]; }
    uint8_t seq() const { return frame_[2]; }
    uint8_t sysid() const { return frame_[3]; }
    uint8_t compid() const { return frame_[4]; }
    uint8_t len() const { return frame_[1]; }
    const uint8_t* payload() const { return frame_ + 6; }
    uint32_t good() const { return good_; }
    uint32_t bad() const { return bad_; }    // rejected candidates (CRC errors, unknown ids, false starts)
private:
    void drop(size_t k);
    uint8_t win_[2 * (kMaxPayload + kOverhead)]{};
    uint8_t frame_[kMaxPayload + kOverhead]{};
    size_t n_{0};
    uint32_t good_{0}, bad_{0};
};

void make_fast(const LogRecord& r, FastPayload& f);

// Frame rates, as dividers of the 500 Hz loop (0 = not sent).
struct Rates {
    uint16_t fast_div{0};
    uint16_t slow_div{0};
};
// t_since_landed_s: seconds since the LANDED state began (ignored in other states).
// budget_level: 0 normal, 1 soft limit reached (lean rates), 2 hard limit (beacon only).
Rates rates_for(FlightState st, float t_since_landed_s, int budget_level);

// Estimated airtime of one frame on a SiK radio at the default 64 kbit/s air rate, counting it as its own radio packet
// (preamble + sync + header + 2-byte trailer, 16 us ticks as in the SiK firmware): an upper bound, because the radio
// packs several frames into one packet whenever more than one is waiting.
float frame_airtime_s(size_t frame_bytes);

// Rolling one-hour estimate of the rocket radio's time on air, in one-minute buckets. A background of 2 % of a whole hour
// (72 s) is always counted for the radio's own link-keeping packets, so the frames themselves are held to what is left.
// Starts with `assumed_s` already "used" (decaying over the first hour): a power cycle cannot hide the airtime of a
// flight flown just before it.
class AirtimeBudget {
public:
    static constexpr float kLimitS = 360.0f;     // 10 % of an hour
    static constexpr float kSoftS = 270.0f;      // above this: lean rates
    static constexpr float kHardS = 330.0f;      // above this: a slow beacon only
    static constexpr float kBackground = 0.02f;
    explicit AirtimeBudget(float assumed_s = 60.0f) : assumed_s_(assumed_s) {}
    void add(float airtime_s) { bucket_[cur_] += airtime_s; }
    void tick(uint32_t now_ms);                  // call regularly (any rate); rolls the buckets once a minute
    float used_s() const;                        // estimated airtime in the last hour, background included
    int level() const;                           // 0 / 1 / 2 as for rates_for()
private:
    float bucket_[60]{};
    int cur_{0};
    uint32_t minute_start_ms_{0};
    uint32_t minutes_{0};                        // whole minutes since start (caps at 60)
    bool started_{false};
    float assumed_s_{0};
};

}  // namespace kestrel::tlm
